// render builds the file for a family. Every value comes from s, so each
// canary appears only in the files that would really hold it.
func render(fam string, s *secrets) string {
	switch fam {
	case famEnv:
		return envFile(s)
	case famGitConfig:
		return fmt.Sprintf("[core]\n\trepositoryformatversion = 0\n\tfilemode = true\n\tbare = false\n\tlogallrefupdates = true\n[remote \"origin\"]\n\turl = https://deploy:%s@%s\n\tfetch = +refs/heads/*:refs/remotes/origin/*\n[branch \"main\"]\n\tremote = origin\n\tmerge = refs/heads/main\n[user]\n\tname = deploy\n\temail = deploy@%s\n",
			s.get("ssh_deploy_password"), s.repo, s.domain)
	case famGitHead:
		return "ref: refs/heads/main\n"
	case famGitLog:
		return gitLog(s)
	case famGitCredentials:
		return fmt.Sprintf("https://deploy:%s@%s\n", s.get("ssh_deploy_password"), strings.SplitN(s.repo, "/", 2)[0])
	case famAWSCredentials:
		return fmt.Sprintf("[default]\naws_access_key_id = %s\naws_secret_access_key = %s\n", s.get("aws_access_key_id"), s.awsSecret())
	case famAWSConfig:
		return "[default]\nregion = us-east-1\noutput = json\n\n[profile deploy]\nregion = us-east-1\nrole_arn = arn:aws:iam::" + s.local("account", "0123456789", 12) + ":role/" + s.app + "-deploy\nsource_profile = default\n"
	case famCompose:
		return composeFile(s)
	case famDockerfile:
		return dockerfile(s)
	case famCredentials:
		return fmt.Sprintf("{\n  \"api\": {\n    \"base_url\": \"%s\",\n    \"key\": \"%s\"\n  },\n  \"aws\": {\n    \"access_key_id\": \"%s\",\n    \"secret_access_key\": \"%s\",\n    \"region\": \"us-east-1\"\n  }\n}\n",
			s.apiBase(), s.get("docs_sample_key"), s.get("aws_access_key_id"), s.awsSecret())
	case famSecrets:
		return fmt.Sprintf("{\n  \"DATABASE_PASSWORD\": \"%s\",\n  \"REDIS_TOKEN\": \"%s\",\n  \"HF_TOKEN\": \"%s\",\n  \"VLLM_API_KEY\": \"%s\"\n}\n",
			s.get("pg_app_password"), s.get("redis_session_token"), s.get("hf_token"), s.get("provider_key_vllm"))
	case famConfigJSON:
		return fmt.Sprintf("{\n  \"name\": \"%s\",\n  \"env\": \"production\",\n  \"apiBaseUrl\": \"%s\",\n  \"apiKey\": \"%s\",\n  \"sentry\": {\"enabled\": false}\n}\n",
			s.app, s.apiBase(), s.get("docs_sample_key"))
	case famConfigJS:
		return fmt.Sprintf("// generated by deploy script - do not commit\nmodule.exports = {\n  env: 'production',\n  apiBaseUrl: '%s',\n  apiKey: '%s',\n  uploadsBucket: '%s',\n};\n",
			s.apiBase(), s.get("docs_sample_key"), s.bucket)
	case famNpmrc:
		return "registry=https://registry.npmjs.org/\n//registry.npmjs.org/:_authToken=npm_" + s.local("npm", alnum, 36) + "\nalways-auth=true\n"
	case famGitlabCI:
		return gitlabCI(s)
	case famWorkflow:
		return workflow(s)
	case famWPConfig:
		return wpConfig(s)
	}
	return ""
}

func (s *secrets) apiBase() string {
	if s.persona {
		return "https://api.demogpu.example/v1"
	}
	return "http://" + s.domain + "/api"
}

func (s *secrets) vllmBase() string {
	if s.persona {
		return "https://vllm.demogpu.example/v1"
	}
	return "http://10.0.3.20:8000/v1"
}

func envFile(s *secrets) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("APP_NAME=%s", s.app)
	w("APP_ENV=production")
	w("APP_DEBUG=false")
	w("APP_URL=https://%s", s.domain)
	w("APP_KEY=base64:%s=", s.local("app_key", b64, 43))
	w("")
	w("DATABASE_URL=postgres://app:%s@%s:5432/%s", s.get("pg_app_password"), s.dbHost, strings.ReplaceAll(s.app, "-", "_"))
	w("REDIS_URL=redis://:%s@%s:6379/0", s.get("redis_session_token"), s.redisHost)
	w("")
	w("# inference")
	w("VLLM_BASE_URL=%s", s.vllmBase())
	w("OPENAI_API_BASE=%s", s.vllmBase())
	w("OPENAI_API_KEY=%s", s.get("provider_key_vllm"))
	w("DEMOGPU_API_KEY=%s", s.get("docs_sample_key"))
	w("HF_TOKEN=%s", s.get("hf_token"))
	w("")
	w("AWS_ACCESS_KEY_ID=%s", s.get("aws_access_key_id"))
	w("AWS_SECRET_ACCESS_KEY=%s", s.awsSecret())
	w("AWS_DEFAULT_REGION=us-east-1")
	w("S3_BUCKET=%s", s.bucket)
	w("")
	w("MAIL_MAILER=smtp")
	w("MAIL_HOST=smtp.%s", s.domain)
	w("MAIL_PORT=587")
	w("LOG_LEVEL=info")
	return b.String()
}

func gitLog(s *secrets) string {
	commits := []string{"0000000000000000000000000000000000000000"}
	for range 4 {
		commits = append(commits, s.rand("0123456789abcdef", 40))
	}
	msgs := []string{"clone: from https://" + s.repo, "pull: Fast-forward", "pull: Fast-forward", "commit: bump worker image, rotate keys"}
	var b strings.Builder
	t := 1733130000
	for i, m := range msgs {
		t += 86400*3 + s.rnd.IntN(86400)
		fmt.Fprintf(&b, "%s %s deploy <deploy@%s> %d +0000\t%s\n", commits[i], commits[i+1], s.domain, t, m)
	}
	return b.String()
}

func composeFile(s *secrets) string {
	return fmt.Sprintf(`services:
  api:
    image: %s/api:2025.01.3
    restart: unless-stopped
    ports:
      - "8000:8000"
    environment:
      DATABASE_URL: postgres://app:%s@db:5432/app
      REDIS_URL: redis://:%s@redis:6379/0
      OPENAI_API_BASE: %s
      OPENAI_API_KEY: %s
    depends_on: [db, redis]

  db:
    image: postgres:16
    restart: unless-stopped
    environment:
      POSTGRES_USER: app
      POSTGRES_PASSWORD: %s
      POSTGRES_DB: app
    volumes:
      - pgdata:/var/lib/postgresql/data

  redis:
    image: redis:7
    command: ["redis-server", "--requirepass", "%s"]

volumes:
  pgdata:
`, s.app, s.get("pg_app_password"), s.get("redis_session_token"), s.vllmBase(), s.get("provider_key_vllm"),
		s.get("pg_app_password"), s.get("redis_session_token"))
}

