func gitlabCI(s *secrets) string {
	return fmt.Sprintf(`stages: [test, build, deploy]

variables:
  AWS_DEFAULT_REGION: us-east-1
  AWS_ACCESS_KEY_ID: %s
  AWS_SECRET_ACCESS_KEY: %s
  IMAGE: registry.%s/%s/api

test:
  stage: test
  image: python:3.11
  script:
    - pip install -r requirements.txt
    - pytest -q

build:
  stage: build
  image: docker:27
  services: [docker:27-dind]
  script:
    - docker build -t $IMAGE:$CI_COMMIT_SHORT_SHA .
    - docker push $IMAGE:$CI_COMMIT_SHORT_SHA

deploy:
  stage: deploy
  only: [main]
  script:
    - aws s3 sync ./static s3://%s/static
    - ssh deploy@%s "docker pull $IMAGE:$CI_COMMIT_SHORT_SHA && docker compose up -d"
`, s.get("aws_access_key_id"), s.awsSecret(), s.domain, s.app, s.bucket, s.domain)
}

func workflow(s *secrets) string {
	return fmt.Sprintf(`name: deploy

on:
  push:
    branches: [main]

env:
  AWS_REGION: us-east-1
  AWS_ACCESS_KEY_ID: %s
  AWS_SECRET_ACCESS_KEY: %s

jobs:
  deploy:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.11"
      - run: pip install -r requirements.txt
      - run: aws s3 sync ./static s3://%s/static --delete
      - name: restart service
        run: sshpass -p "%s" ssh -o StrictHostKeyChecking=no deploy@%s "cd /srv/%s && git pull && docker compose up -d --build"
`, s.get("aws_access_key_id"), s.awsSecret(), s.bucket, s.get("ssh_deploy_password"), s.domain, s.app)
}

func wpConfig(s *secrets) string {
	var b strings.Builder
	b.WriteString("<?php\n/**\n * The base configuration for WordPress\n *\n * @package WordPress\n */\n\n")
	b.WriteString("// ** Database settings ** //\n")
	fmt.Fprintf(&b, "define( 'DB_NAME', 'wordpress' );\ndefine( 'DB_USER', 'wp_app' );\ndefine( 'DB_PASSWORD', '%s' );\ndefine( 'DB_HOST', 'localhost' );\ndefine( 'DB_CHARSET', 'utf8mb4' );\ndefine( 'DB_COLLATE', '' );\n\n",
		s.get("pg_app_password"))
	for _, k := range []string{"AUTH_KEY", "SECURE_AUTH_KEY", "LOGGED_IN_KEY", "NONCE_KEY", "AUTH_SALT", "SECURE_AUTH_SALT", "LOGGED_IN_SALT", "NONCE_SALT"} {
		fmt.Fprintf(&b, "define( '%s',%s'%s' );\n", k, strings.Repeat(" ", 17-len(k)), s.local(k, alnum+"!@#$%^&*()-_[]{}<>~+=,.;:/?|", 64))
	}
	fmt.Fprintf(&b, "\n// offload media\ndefine( 'AS3CF_SETTINGS', serialize( array(\n\t'provider' => 'aws',\n\t'access-key-id' => '%s',\n\t'secret-access-key' => '%s',\n) ) );\n\n",
		s.get("aws_access_key_id"), s.awsSecret())
	b.WriteString("$table_prefix = 'wp_';\n\ndefine( 'WP_DEBUG', false );\n\nif ( ! defined( 'ABSPATH' ) ) {\n\tdefine( 'ABSPATH', __DIR__ . '/' );\n}\n\nrequire_once ABSPATH . 'wp-settings.php';\n")
	return b.String()
}
